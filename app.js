// ── Lightbox ──
let currentIndex = 0;
let activePhotos = [];

function openLightbox(index, photoSet) {
  activePhotos = photoSet || photos.map(p => p.src);
  currentIndex = index;
  document.getElementById('lb-img').src = activePhotos[index];
  document.getElementById('lightbox').classList.add('open');
  document.body.style.overflow = 'hidden';
  document.querySelector('.lb-actions').style.display = 'flex';
  updateLikeUI();
}

function closeLightbox() {
  document.getElementById('lightbox').classList.remove('open');
  document.body.style.overflow = '';
}

function openBuyPopup() {
  document.getElementById('buyPopup').classList.add('open');
}

function closeBuyPopup() {
  document.getElementById('buyPopup').classList.remove('open');
}

function moveLight(dir) {
  currentIndex = (currentIndex + dir + activePhotos.length) % activePhotos.length;
  document.getElementById('lb-img').src = activePhotos[currentIndex];
  updateLikeUI();
}

document.addEventListener('keydown', e => {
  if (!document.getElementById('lightbox').classList.contains('open')) return;
  if (e.key === 'Escape')     { closeLightbox(); closeBuyPopup(); }
  if (e.key === 'ArrowRight') moveLight(1);
  if (e.key === 'ArrowLeft')  moveLight(-1);
});

